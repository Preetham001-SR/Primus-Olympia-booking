/** Spring-blend through keyframes: each key starts easing in at its frame. */
const keyed = <T extends Record<string, number>>(frame: number, keys: [number, T][]): T => {
	let cur = { ...keys[0][1] };
	for (const [f, v] of keys.slice(1)) {
		const t = sp(frame, f, { mass: 1.3 });
		for (const k in v) (cur as Record<string, number>)[k] = mix(cur[k], v[k], t);
	}
	return cur;
};

