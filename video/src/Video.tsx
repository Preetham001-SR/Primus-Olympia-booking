export const Video: React.FC = () => {
	const { height, fps } = useVideoConfig();
	const frame = (useCurrentFrame() * 30) / fps; // timeline below is authored in 30fps beats
	const L = height === 1080 ? SQUARE : VERTICAL;
	const pose = keyed(frame, L.poses);

	const scroll = keyed(frame, [
		[0, { v: 0 }],
		[96, { v: S.stripBtn.y - 430 }],
		[186, { v: S.pcVisit.y }],
		[268, { v: S.card.y - 100 }],
	]).v;
	const cut = frame >= 360 ? Math.min(3, Math.floor((frame - 360) / 30)) : -1;

	return (
		<AbsoluteFill style={{ fontFamily: BODY, color: C.text }}>
			<Audio src={staticFile('audio/soundtrack.wav')} />{/* generated by scripts/make_audio.py */}
			<Background frame={frame} drift={pose.y} />

			{frame < 480 && (
				<Phone pose={pose}>
					{cut < 0 ? <Page scroll={scroll} /> : <Cuts frame={frame} cut={cut} />}
					{cut < 0 && <PhoneOverlays frame={frame} scroll={scroll} />}
				</Phone>
			)}

			{frame < 140 && <Hook frame={frame} L={L} />}
			{frame >= 132 && frame < 180 && <Offer frame={frame} L={L} />}
			{frame >= 180 && frame < 360 && <HowItWorks frame={frame} L={L} />}
			{frame >= 360 && frame < 480 && <Captions frame={frame} L={L} />}
			{frame >= 480 && <EndCard frame={frame} L={L} />}
		</AbsoluteFill>
	);
};

/* ---------- Background: soft tint with slow parallax blobs ---------- */

const Background: React.FC<{ frame: number; drift: number }> = ({ frame, drift }) => {
	const { width, height } = useVideoConfig();
	const p = (drift - height / 2) * 0.06;
	const blob = (x: number, y: number, r: number, a: number) => (
		<div style={{ position: 'absolute', left: x - r, top: y - r, width: r * 2, height: r * 2, borderRadius: '50%', background: `radial-gradient(circle, rgba(139,47,92,${a}) 0%, rgba(139,47,92,0) 70%)` }} />
	);
	return (
		<AbsoluteFill style={{ background: `linear-gradient(180deg, ${C.white} 0%, ${C.tint} 100%)`, overflow: 'hidden' }}>
			{blob(width * 0.15 + Math.sin(frame / 70) * 30, height * 0.25 - p, width * 0.45, 0.1)}
			{blob(width * 0.9 + Math.cos(frame / 90) * 30, height * 0.7 - p * 1.8, width * 0.5, 0.09)}
			{blob(width * 0.55, height * 1.05 - p * 0.6, width * 0.6, 0.07)}
		</AbsoluteFill>
	);
};

